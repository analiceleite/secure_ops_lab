\set ON_ERROR_STOP on
\getenv meta_password FIXTURE_META_PASSWORD
\getenv ingest_password FIXTURE_INGEST_PASSWORD
SET log_min_error_statement = 'panic';
SET log_statement = 'none';
CREATE ROLE n8n_meta LOGIN PASSWORD :'meta_password' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE incident_owner NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE incident_ingest LOGIN PASSWORD :'ingest_password' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE incident_reader NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE incident_report NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE;
ALTER ROLE incident_ingest SET statement_timeout = '5s';
CREATE DATABASE n8n OWNER n8n_meta;
REVOKE ALL ON DATABASE n8n FROM PUBLIC;
GRANT CONNECT ON DATABASE n8n TO n8n_meta;
CREATE DATABASE incidents OWNER incident_owner;
REVOKE ALL ON DATABASE incidents FROM PUBLIC;
GRANT CONNECT ON DATABASE incidents TO incident_ingest;
\connect n8n
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT ALL ON SCHEMA public TO n8n_meta;
\connect incidents
REVOKE ALL ON SCHEMA public FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE incident_owner REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
